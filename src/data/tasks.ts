/** Tasks still open, soonest deadline first. */
export function openTasks(): Task[] {
  return tasks
    .filter((task) => task.status !== "done")
    .sort((a, b) => a.due.localeCompare(b.due) || a.title.localeCompare(b.title));
}

/** Tasks due within the inclusive date range. */
export function tasksDueBetween(from: string, to: string): Task[] {
  return tasks.filter((task) => task.due >= from && task.due <= to);
}
